create table catfisha_typhoons.hurricane_names (
  id     integer generated by default as identity primary key,
  set    smallint not null check (set between 0 and 6),  -- year % 6; 6 = supplemental list
  basin  char(1) not null check (basin in ('L', 'E')),
  seq    smallint not null check (seq > 0),               -- 1-based order within the list
  name   text not null,
  unique (set, basin, seq),
  unique (set, basin, name)
);

alter table catfisha_typhoons.hurricane_names enable row level security;

create policy "Hurricane names are publicly readable"
  on catfisha_typhoons.hurricane_names for select
  using (true);

grant select on catfisha_typhoons.hurricane_names to anon, authenticated;

