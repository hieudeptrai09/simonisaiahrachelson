create schema if not exists catfisha_typhoons;

create table catfisha_typhoons.hurricanes (
  id       integer generated by default as identity primary key,
  year     smallint not null,
  name     text not null,
  basin    char(1) not null check (basin in ('L', 'E')),
  ts_date  date not null,                        -- first fix with max wind >= 35 kt
  unique (year, basin, name)
);

alter table catfisha_typhoons.hurricanes enable row level security;

create policy "Hurricanes are publicly readable"
  on catfisha_typhoons.hurricanes for select
  using (true);

-- Custom schemas are not granted to the API roles automatically. Read-only: data is
-- written from the SQL Editor (as the table owner), never through the API.
grant usage on schema catfisha_typhoons to anon, authenticated;
grant select on catfisha_typhoons.hurricanes to anon, authenticated;
