-- Names taken off the rotating lists, with the season of the storm that retired them
-- (for names removed without a storm cause, the season the name was last used).
-- Source: Wikipedia's lists of retired Atlantic / Pacific hurricane names, cross-checked
-- against catfisha_typhoons.hurricanes for every season from 1966 on.
create table catfisha_typhoons.hurricane_retired (
  id     integer generated by default as identity primary key,
  name   text not null,
  year   smallint not null,
  basin  char(1) not null check (basin in ('L', 'E')),
  unique (basin, name)
);

alter table catfisha_typhoons.hurricane_retired enable row level security;

create policy "Retired hurricane names are publicly readable"
  on catfisha_typhoons.hurricane_retired for select
  using (true);

grant select on catfisha_typhoons.hurricane_retired to anon, authenticated;

